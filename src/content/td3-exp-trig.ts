/** Detailed discriminant calculations for the two reviewed quadratics in exercise 4. */
function quadraticCorrection(a: 1 | 2, b: -1 | -5, c: -2 | 2): Step[] {
  const square = b * b, firstProduct = 4 * a, product = 4 * a * c;
  const delta = square - product;
  if (delta !== 9) throw new Error('The exercise 4 correction expects discriminant 9.');
  const signedC = c < 0 ? `(${c})` : `${c}`;
  const signedProduct = product < 0 ? `(${product})` : `${product}`;
  const initial = t`(${b})^2-4\times${a}\times${signedC}`;
  const squared = t`${square}-4\times${a}\times${signedC}`;
  const first = t`${square}-${firstProduct}\times${signedC}`;
  const second = `${square}-${signedProduct}`;
  const simplified = product < 0 ? `${square}+${-product}` : second;
  const out: Step[] = [
    step('Identifier les coefficients', t`a=${a},\quad b=${b},\quad c=${c}`,
      'On compare le polynôme à aX² + bX + c. On conserve le signe de chaque coefficient ; a est non nul.',
      { phase: 'Résolution par le discriminant', statement: true }),
    step('La formule du discriminant', t`\Delta=b^2-4ac`,
      'Pour une équation du second degré aX² + bX + c = 0, le discriminant est Δ = b² − 4ac.',
      { statement: true }),
    step('Remplacer les coefficients', t`\Delta=${initial}`,
      `On remplace a par ${a}, b par ${b} et c par ${c}. Les parenthèses gardent le signe de b dans son carré.`),
    step('Calculer le carré de b', t`\Delta=${squared}`,
      `Le carré de ${b} vaut ${square}. Le signe moins devant 4ac reste inchangé.`,
      { fromFocus: `(${b})^2`, focus: `${square}`, simplify: { source: `(${b})^2`, result: `${square}`, rule: 'Carré d’un nombre négatif' } }),
    step('Calculer 4a', t`\Delta=${first}`,
      `On calcule d’abord 4 × ${a} = ${firstProduct}.`,
      { fromFocus: t`4\times${a}`, focus: `${firstProduct}`, product: { left: '4', right: `${a}`, result: `${firstProduct}` } }),
    step('Calculer le produit par c', t`\Delta=${second}`,
      `Le produit ${firstProduct} × (${c}) vaut ${product}. Il est soustrait dans la formule du discriminant.`,
      { fromFocus: t`${firstProduct}\times${signedC}`, focus: signedProduct, product: { left: `${firstProduct}`, right: `${c}`, result: signedProduct } }),
  ];
  if (product < 0) out.push(step('Soustraire un nombre négatif', t`\Delta=${simplified}`,
    'Soustraire −8 revient à ajouter 8.',
    { fromFocus: '-(-8)', focus: '+8', simplify: { source: '-(-8)', result: '+8', rule: 'Soustraire l’opposé d’un nombre' } }));
  out.push(
    step('La valeur du discriminant', t`\Delta=9`,
      'Le discriminant est strictement positif : l’équation du second degré admet deux racines réelles distinctes.',
      { fromFocus: simplified, focus: '9', simplify: { source: simplified, result: '9', rule: 'Calculer le discriminant' } }),
    step('La racine carrée du discriminant', t`\sqrt\Delta=3`,
      'Le nombre 3 est strictement positif et son carré vaut 9. Ainsi, √Δ = 3.',
      { statement: true }),
  );
  for (const [index, sign] of ['-', '+'].entries()) {
    const prefix = `X_${index + 1}=`;
    const numerator = -b + (sign === '-' ? -3 : 3);
    const denominator = 2 * a;
    const result = a === 2 && index === 0 ? t`\frac12` : `${numerator / denominator}`;
    const firstFraction = t`\frac{${-b}${sign}3}{2\times${a}}`;
    const secondFraction = t`\frac{${-b}${sign}3}{${denominator}}`;
    const thirdFraction = t`\frac{${numerator}}{${denominator}}`;
    out.push(
      step(index === 0 ? 'La formule de la première racine' : 'La formule de la seconde racine',
        prefix + t`\frac{-b${sign}\sqrt\Delta}{2a}`,
        `Comme a ≠ 0 et Δ > 0, on utilise la formule avec le signe ${sign === '-' ? 'moins' : 'plus'} devant √Δ.`,
        { phase: index === 0 ? 'Calcul des deux racines' : undefined, statement: true }),
      step('Remplacer les valeurs connues', prefix + firstFraction,
        `On a −b = ${-b}, √Δ = 3 et a = ${a}. Le dénominateur divise tout le numérateur.`),
      step('Calculer le dénominateur', prefix + secondFraction,
        `Le dénominateur vaut 2 × ${a} = ${denominator}.`,
        { fromFocus: t`2\times${a}`, focus: secondFraction, simplify: { source: t`2\times${a}`, result: `${denominator}`, rule: 'Calculer le dénominateur' } }),
      step('Calculer le numérateur', prefix + thirdFraction,
        `Le numérateur vaut ${-b} ${sign === '-' ? '−' : '+'} 3 = ${numerator}.`,
        { fromFocus: `${-b}${sign}3`, focus: `${numerator}`, simplify: { source: `${-b}${sign}3`, result: `${numerator}`, rule: 'Calculer le numérateur' } }),
      step(index === 0 ? 'La première racine' : 'La seconde racine', prefix + result,
        a === 2 && index === 0 ? 'On divise le numérateur et le dénominateur de 2/4 par 2 : on obtient 1/2.' : `Le quotient ${numerator}/${denominator} vaut ${numerator / denominator}.`,
        { fromFocus: thirdFraction, focus: result, focusOccurrence: result === '2' && index === 1 ? 2 : undefined, simplify: { source: thirdFraction, result, rule: 'Simplifier le quotient', condition: `${denominator}\\ne0` } }),
    );
  }
  return out;
}

